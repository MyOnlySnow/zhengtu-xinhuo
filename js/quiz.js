function shuffled(rows, random) {
  const result=[...rows];
  for(let i=result.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[result[i],result[j]]=[result[j],result[i]];}
  return result;
}

// 混合抽题按主题轮流取题，避免一轮题目集中在一个主题。
export function drawQuiz({topic='全部',count=10,random=Math.random}={}) {
  const pool=QUIZ.filter(q=>topic==='全部'||q.topic===topic);
  const limit=count==='all'?pool.length:Math.min(pool.length,Math.max(1,Number(count)||10));
  const groups=shuffled(QUIZ_TOPICS.filter(t=>pool.some(q=>q.topic===t)),random)
    .map(t=>shuffled(pool.filter(q=>q.topic===t),random));
  const result=[];
  while(result.length<limit){
    for(const group of groups){
      if(group.length&&result.length<limit)result.push(group.pop());
    }
  }
  return result;
}

export function questionResult(question, selected=[]) {
  const values=[...new Set(selected.map(Number))].sort((a,b)=>a-b);
  if(!values.length)return 'unanswered';
  const answers=[...question.answers].sort((a,b)=>a-b);
  return values.length===answers.length&&values.every((value,i)=>value===answers[i])?'correct':'wrong';
}

export function gradeQuiz(questions, responses) {
  const results=questions.map(q=>({id:q.id,status:questionResult(q,responses[q.id]||[])}));
  return {
    results,
    correct:results.filter(r=>r.status==='correct').length,
    wrong:results.filter(r=>r.status==='wrong').length,
    unanswered:results.filter(r=>r.status==='unanswered').length,
  };
}
